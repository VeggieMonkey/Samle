"""Master build script for Samle.

Usage
-----
  python build/build.py                # EXE only (PyInstaller)
  python build/build.py --full         # EXE + installer (requires Inno Setup 6)
  python build/build.py --clean        # Remove previous build artefacts, then build
  python build/build.py --full --clean # Clean, build EXE, build installer

Environment
-----------
  ISCC_PATH  – override path to ISCC.exe if not in one of the default locations
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT  = Path(__file__).parent.parent
SPEC  = ROOT / "build" / "samle_pdf.spec"
DIST  = ROOT / "dist"
WORK  = ROOT / "build" / "_work"
ISS   = ROOT / "installer" / "samle_pdf.iss"

ISCC_CANDIDATES = [
    Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
    Path(r"C:\Program Files\Inno Setup 6\ISCC.exe"),
]

# ── Terminal colour helpers ────────────────────────────────────────────────

def _c(code: str, text: str) -> str:
    """Wrap text in ANSI colour if stdout is a tty."""
    if not sys.stdout.isatty():
        return text
    return f"\033[{code}m{text}\033[0m"

ok    = lambda t: print(_c("92", f"  ✓  {t}"))
info  = lambda t: print(_c("94", f"  ·  {t}"))
warn  = lambda t: print(_c("93", f"  !  {t}"))
err   = lambda t: print(_c("91", f"  ✗  {t}"), file=sys.stderr)
head  = lambda t: print(_c("1;97", f"\n{'═' * 54}\n  {t}\n{'═' * 54}"))


# ── Version helpers ────────────────────────────────────────────────────────

def _get_version() -> str:
    """Return version from git tag, falling back to pyproject.toml."""
    # 1. Git tag (used in CI and local tagged builds)
    try:
        result = subprocess.run(
            ["git", "describe", "--tags", "--abbrev=0"],
            capture_output=True, text=True, cwd=ROOT,
        )
        if result.returncode == 0:
            tag = result.stdout.strip().lstrip("v")
            if tag:
                return tag
    except Exception:
        pass

    # 2. pyproject.toml fallback
    try:
        import tomllib  # Python 3.11+
        with open(ROOT / "pyproject.toml", "rb") as f:
            data = tomllib.load(f)
        return data["project"]["version"]
    except Exception:
        pass

    return "0.0.0"


def _version_tuple(version: str) -> tuple[int, int, int, int]:
    """Convert 'X.Y.Z' to a 4-tuple for Windows VERSIONINFO."""
    parts = version.split(".")
    ints = []
    for p in parts[:3]:
        try:
            ints.append(int(p))
        except ValueError:
            ints.append(0)
    while len(ints) < 4:
        ints.append(0)
    return tuple(ints[:4])  # type: ignore[return-value]


def step_write_version(version: str) -> None:
    """Write version into all generated version files."""
    head(f"Version: {version}")

    # 1. src/combiner/_version.py  (read at runtime by the app)
    version_py = ROOT / "src" / "combiner" / "_version.py"
    version_py.write_text(
        f"# This file is generated by build/build.py — do not edit manually.\n"
        f'__version__ = "{version}"\n',
        encoding="utf-8",
    )
    ok(f"Wrote {version_py.relative_to(ROOT)}")

    # 2. build/version_info.py  (read by PyInstaller for EXE VERSIONINFO)
    vt = _version_tuple(version)
    vt_str = f"{vt[0]}.{vt[1]}.{vt[2]}.{vt[3]}"
    version_info_py = ROOT / "build" / "version_info.py"
    version_info_py.write_text(
        f"# Generated by build/build.py — do not edit manually.\n"
        f"# fmt: off\n"
        f"VSVersionInfo(\n"
        f"  ffi=FixedFileInfo(\n"
        f"    filevers={vt},\n"
        f"    prodvers={vt},\n"
        f"    mask=0x3f,\n"
        f"    flags=0x0,\n"
        f"    OS=0x40004,\n"
        f"    fileType=0x1,\n"
        f"    subtype=0x0,\n"
        f"    date=(0, 0),\n"
        f"  ),\n"
        f"  kids=[\n"
        f"    StringFileInfo([\n"
        f"      StringTable(\n"
        f'        "040904B0",\n'
        f"        [\n"
        f'          StringStruct("CompanyName",      "VeggieMonkey"),\n'
        f'          StringStruct("FileDescription",  "Samle PDF-filer med ett klikk"),\n'
        f'          StringStruct("FileVersion",      "{vt_str}"),\n'
        f'          StringStruct("InternalName",     "samle_pdf"),\n'
        f'          StringStruct("LegalCopyright",   "MIT License"),\n'
        f'          StringStruct("OriginalFilename", "samle_pdf.exe"),\n'
        f'          StringStruct("ProductName",      "Samle"),\n'
        f'          StringStruct("ProductVersion",   "{vt_str}"),\n'
        f"        ]\n"
        f"      ),\n"
        f"    ]),\n"
        f"    VarFileInfo([VarStruct(\"Translation\", [0x0409, 1200])]),\n"
        f"  ]\n"
        f")\n"
        f"# fmt: on\n",
        encoding="utf-8",
    )
    ok(f"Wrote {version_info_py.relative_to(ROOT)}")


# ── Helpers ────────────────────────────────────────────────────────────────

def _run(cmd: list[str | Path], **kwargs) -> None:
    info(" ".join(str(c) for c in cmd))
    t0 = time.monotonic()
    result = subprocess.run(cmd, **kwargs)
    elapsed = time.monotonic() - t0
    if result.returncode != 0:
        err(f"Command failed (exit {result.returncode})")
        sys.exit(result.returncode)
    ok(f"Done in {elapsed:.1f}s")


def _find_iscc() -> Path | None:
    # 1. Env override
    env = os.environ.get("ISCC_PATH")
    if env and Path(env).exists():
        return Path(env)
    # 2. Well-known install paths
    for c in ISCC_CANDIDATES:
        if c.exists():
            return c
    # 3. PATH
    found = shutil.which("ISCC")
    return Path(found) if found else None


# ── Steps ──────────────────────────────────────────────────────────────────

def step_clean() -> None:
    head("Clean")
    for d in [DIST / "samle_pdf", DIST / "installer", WORK]:
        if d.exists():
            shutil.rmtree(d)
            ok(f"Removed {d.relative_to(ROOT)}")
    ok("Clean complete")


def step_assets(version: str) -> None:
    head("Generate assets")
    env = os.environ.copy()
    env["SAMLE_VERSION"] = version
    _run([sys.executable, str(ROOT / "build" / "generate_assets.py")], env=env)


def step_pyinstaller() -> None:
    head("Build EXE  (PyInstaller)")
    _run([
        sys.executable, "-m", "PyInstaller",
        "--clean",
        "--noconfirm",
        str(SPEC),
        "--distpath", str(DIST),
        "--workpath", str(WORK),
    ])

    exe = DIST / "samle_pdf" / "samle_pdf.exe"
    if not exe.exists():
        err(f"Expected EXE not found: {exe}")
        sys.exit(1)

    size_mb = exe.stat().st_size / 1_048_576
    ok(f"EXE built: {exe.relative_to(ROOT)}  ({size_mb:.1f} MB)")


def step_inno(version: str) -> None:
    head("Build installer  (Inno Setup)")
    iscc = _find_iscc()
    if iscc is None:
        err(
            "ISCC.exe not found.\n"
            "  Install Inno Setup 6 from https://jrsoftware.org/isinfo.php\n"
            "  or set ISCC_PATH=/path/to/ISCC.exe"
        )
        sys.exit(1)

    out_dir = DIST / "installer"
    out_dir.mkdir(parents=True, exist_ok=True)

    _run([str(iscc), f"/DAppVersion={version}", str(ISS)])

    setup_exe = next(out_dir.glob("*.exe"), None)
    if setup_exe:
        size_mb = setup_exe.stat().st_size / 1_048_576
        ok(f"Installer: {setup_exe.relative_to(ROOT)}  ({size_mb:.1f} MB)")
    else:
        warn("Installer EXE not found in dist/installer/ — check Inno Setup output.")


# ── Entry point ────────────────────────────────────────────────────────────

def main() -> None:
    args = sys.argv[1:]
    clean = "--clean" in args
    full  = "--full"  in args

    os.chdir(ROOT)

    version = _get_version()

    if clean:
        step_clean()

    step_write_version(version)

    # Re-generate assets if icon is missing
    if not (ROOT / "assets" / "icon.ico").exists():
        step_assets(version)

    step_pyinstaller()

    if full:
        step_inno(version)

    head("Build complete")
    exe = DIST / "samle_pdf" / "samle_pdf.exe"
    ok(f"EXE → {exe.relative_to(ROOT)}")
    if full:
        setup_exe = next((DIST / "installer").glob("*.exe"), None)
        if setup_exe:
            ok(f"Installer → {setup_exe.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
